#!/usr/bin/env node
// Generates CSS custom properties from design/tokens.json.
// Usage: node design/scripts/build-tokens.mjs [--check]
//   default  writes app/tokens.css
//   --check  exits 1 if the committed CSS is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokensPath = join(here, '..', 'tokens.json');
const outPath = join(here, '..', '..', 'app', 'tokens.css');

export function buildCss(tokens) {
  const lines = [];
  const decl = (name, value) => `  --${name}: ${value};`;
  const colorBlock = (theme) =>
    Object.entries(theme).map(([k, v]) => decl(`color-${k}`, v));
  const elevationBlock = (e) => Object.entries(e).map(([k, v]) => decl(`elevation-${k}`, v));

  lines.push('/* Generated by design/scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */');
  lines.push(`/* Design system v${tokens.version} — ${tokens.status} */`);
  lines.push('');
  lines.push(':root {');
  const t = tokens.typography;
  lines.push(decl('font-sans', t.fontFamily.sans));
  lines.push(decl('font-mono', t.fontFamily.mono));
  for (const [k, v] of Object.entries(t.scale)) {
    lines.push(decl(`text-${k}`, v.size));
    lines.push(decl(`leading-${k}`, v.lineHeight));
  }
  for (const [k, v] of Object.entries(t.weight)) lines.push(decl(`weight-${k}`, v));
  for (const [k, v] of Object.entries(tokens.space)) lines.push(decl(`space-${k}`, v));
  for (const [k, v] of Object.entries(tokens.radius)) lines.push(decl(`radius-${k}`, v));
  for (const [k, v] of Object.entries(tokens.motion.duration)) lines.push(decl(`duration-${k}`, v));
  for (const [k, v] of Object.entries(tokens.motion.easing)) lines.push(decl(`ease-${k}`, v));
  for (const [k, v] of Object.entries(tokens.size)) lines.push(decl(`size-${k}`, v));
  for (const [k, v] of Object.entries(tokens.zIndex)) lines.push(decl(`z-${k}`, v));
  lines.push('');
  lines.push(`  /* ${tokens.defaultTheme} theme (default) */`);
  lines.push(`  color-scheme: ${tokens.defaultTheme};`);
  lines.push(...colorBlock(tokens.color.themes[tokens.defaultTheme]));
  lines.push(...elevationBlock(tokens.elevation[tokens.defaultTheme]));
  lines.push('}');
  lines.push('');
  const light = [
    '  color-scheme: light;',
    ...colorBlock(tokens.color.themes.light),
    ...elevationBlock(tokens.elevation.light),
  ];
  lines.push(':root[data-theme="light"] {', ...light, '}');
  lines.push('');
  lines.push('@media (prefers-color-scheme: light) {');
  lines.push('  :root[data-theme="system"] {', ...light.map((l) => '  ' + l), '  }');
  lines.push('}');
  lines.push('');
  lines.push('@media (prefers-reduced-motion: reduce) {');
  lines.push('  :root {');
  for (const [k, v] of Object.entries(tokens.motion.reducedMotion.duration)) {
    lines.push('  ' + decl(`duration-${k}`, v));
  }
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const tokens = JSON.parse(readFileSync(tokensPath, 'utf8'));
  const css = buildCss(tokens);
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(outPath, 'utf8');
    } catch {
      /* missing file counts as stale */
    }
    if (current !== css) {
      console.error('app/tokens.css is out of date. Run: node design/scripts/build-tokens.mjs');
      process.exit(1);
    }
    console.log('tokens.css is up to date.');
  } else {
    writeFileSync(outPath, css);
    console.log(`Wrote ${outPath}`);
  }
}
