#!/usr/bin/env node
// Generates CSS custom properties from design/tokens.json.
// Usage: node design/scripts/build-tokens.mjs [--check]
//   default  writes app/tokens.css and app/studio/studio-tokens.css
//   --check  exits 1 if either committed CSS file is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokensPath = join(here, '..', 'tokens.json');
const outPath = join(here, '..', '..', 'app', 'tokens.css');
const studioOutPath = join(here, '..', '..', 'app', 'studio', 'studio-tokens.css');

export function buildCss(tokens) {
  const lines = [];
  const decl = (name, value) => `  --${name}: ${value};`;
  const colorBlock = (theme) =>
    Object.entries(theme).map(([k, v]) => decl(`color-${k}`, v));
  const elevationBlock = (e) => Object.entries(e).map(([k, v]) => decl(`elevation-${k}`, v));

  lines.push('/* Generated by design/scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */');
  lines.push(`/* Design system v${tokens.version} — ${tokens.status} */`);
  lines.push('');
  lines.push(':root {');
  const t = tokens.typography;
  lines.push(decl('font-sans', t.fontFamily.sans));
  lines.push(decl('font-mono', t.fontFamily.mono));
  for (const [k, v] of Object.entries(t.scale)) {
    lines.push(decl(`text-${k}`, v.size));
    lines.push(decl(`leading-${k}`, v.lineHeight));
  }
  for (const [k, v] of Object.entries(t.weight)) lines.push(decl(`weight-${k}`, v));
  for (const [k, v] of Object.entries(tokens.space)) lines.push(decl(`space-${k}`, v));
  for (const [k, v] of Object.entries(tokens.radius)) lines.push(decl(`radius-${k}`, v));
  for (const [k, v] of Object.entries(tokens.motion.duration)) lines.push(decl(`duration-${k}`, v));
  for (const [k, v] of Object.entries(tokens.motion.easing)) lines.push(decl(`ease-${k}`, v));
  for (const [k, v] of Object.entries(tokens.size)) lines.push(decl(`size-${k}`, v));
  for (const [k, v] of Object.entries(tokens.zIndex)) lines.push(decl(`z-${k}`, v));
  lines.push('');
  lines.push(`  /* ${tokens.defaultTheme} theme (default) */`);
  lines.push(`  color-scheme: ${tokens.defaultTheme};`);
  lines.push(...colorBlock(tokens.color.themes[tokens.defaultTheme]));
  lines.push(...elevationBlock(tokens.elevation[tokens.defaultTheme]));
  lines.push('}');
  lines.push('');
  const light = [
    '  color-scheme: light;',
    ...colorBlock(tokens.color.themes.light),
    ...elevationBlock(tokens.elevation.light),
  ];
  lines.push(':root[data-theme="light"] {', ...light, '}');
  lines.push('');
  lines.push('@media (prefers-color-scheme: light) {');
  lines.push('  :root[data-theme="system"] {', ...light.map((l) => '  ' + l), '  }');
  lines.push('}');
  lines.push('');
  lines.push('@media (prefers-reduced-motion: reduce) {');
  lines.push('  :root {');
  for (const [k, v] of Object.entries(tokens.motion.reducedMotion.duration)) {
    lines.push('  ' + decl(`duration-${k}`, v));
  }
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/** The Studio's custom properties, scoped under `.studio`. */
export function buildStudioCss(tokens) {
  const s = tokens.studio;
  const lines = [];
  const decl = (name, value) => `  --${name}: ${value};`;
  lines.push('/* Generated by design/scripts/build-tokens.mjs from design/tokens.json (color.themes.studio, studio). Do not edit by hand. */');
  lines.push('');
  lines.push('.studio {');
  lines.push('  /* colour */');
  for (const [k, v] of Object.entries(tokens.color.themes.studio)) lines.push(decl(k, v.toLowerCase()));
  lines.push('  /* space, radius, elevation */');
  for (const [k, v] of Object.entries(s.space)) lines.push(decl(`space-${k}`, v));
  for (const [k, v] of Object.entries(s.radius)) lines.push(decl(`radius-${k}`, v));
  for (const [k, v] of Object.entries(s.shadow)) lines.push(decl(`shadow-${k}`, v));
  lines.push('  /* motion */');
  for (const [k, v] of Object.entries(s.motion)) lines.push(decl(k, v));
  lines.push('  /* type */');
  for (const [k, v] of Object.entries(s.font)) lines.push(decl(`font-${k}`, v));
  for (const [k, v] of Object.entries(s.type)) {
    lines.push(decl(`t-${k}`, v.size), decl(`t-${k}-lh`, v.lh), decl(`t-${k}-fa`, v['fa-size']), decl(`t-${k}-fa-lh`, v['fa-lh']), decl(`t-${k}-w`, v.weight));
  }
  lines.push('  /* sizes */');
  for (const [k, v] of Object.entries(s.size)) lines.push(decl(`size-${k}`, v));
  lines.push('  --dir: 1;');
  lines.push('}');
  lines.push('[dir="rtl"] .studio,');
  lines.push('.studio[dir="rtl"] {');
  lines.push('  --dir: -1;');
  lines.push('}');
  lines.push('');
  lines.push('@media (prefers-reduced-motion: reduce) {');
  lines.push('  .studio {');
  for (const [k, v] of Object.entries(s.reducedMotion)) lines.push('  ' + decl(k, v));
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const tokens = JSON.parse(readFileSync(tokensPath, 'utf8'));
  const outputs = [
    [outPath, buildCss(tokens)],
    [studioOutPath, buildStudioCss(tokens)],
  ];
  if (process.argv.includes('--check')) {
    let stale = false;
    for (const [file, css] of outputs) {
      let current = '';
      try {
        current = readFileSync(file, 'utf8');
      } catch {
        /* missing file counts as stale */
      }
      if (current !== css) {
        console.error(`${relative(join(here, '..', '..'), file)} is out of date. Run: node design/scripts/build-tokens.mjs`);
        stale = true;
      }
    }
    if (stale) process.exit(1);
    console.log('tokens.css and studio-tokens.css are up to date.');
  } else {
    for (const [file, css] of outputs) {
      writeFileSync(file, css);
      console.log(`Wrote ${file}`);
    }
  }
}
